// auto count
const int layerCount = sizeof(layers) / sizeof(Layer);

// temp buffer (KEY)
Layer L_temp;

// ===== HELPERS =====
bool active(Layer &L, unsigned long t) {
  return (t >= L.start && t <= L.end);
}

float weight(Layer &L, unsigned long t) {
  unsigned long local = t - L.start;
  unsigned long total = L.end - L.start;

  if (L.fade_in > 0 && local < L.fade_in)
    return (float)local / L.fade_in;

  if (L.fade_out > 0 && local > total - L.fade_out)
    return 1.0 - (float)(local - (total - L.fade_out)) / L.fade_out;

  return 1.0;
}

// ===== SETUP =====
void setup() {
  Serial.begin(115200);

  for (int i=0;i<N_PUMPS;i++) pinMode(pumpPins[i], OUTPUT);
  for (int i=0;i<N_MOTORS;i++) motors[i].attach(motorPins[i]);
}

// ===== LOOP =====
void loop() {
  t = millis() % 80000;

  float motor_out[N_MOTORS] = {90,90,90};
  float pump_out[N_PUMPS] = {0,0,0};

  // ===== MOTORS =====
  for (int i=0;i<N_MOTORS;i++) {
    float cur = -1;

    for (int j=0;j<layerCount;j++) {

      // 🔥 READ FROM FLASH
      memcpy_P(&L_temp, &layers[j], sizeof(Layer));
      Layer &L = L_temp;

      if (!active(L,t) || L.motors[i]==-1) continue;

      float w = weight(L,t);
      float target = L.motors[i] + L.motion(i,t);

      cur = (cur<0)?target:(cur*(1-w)+target*w);
    }

    if (cur>=0) motor_out[i]=cur;
  }

  // ===== PUMPS =====
  for (int i=0;i<N_PUMPS;i++) {
    float cur = -1;

    for (int j=0;j<layerCount;j++) {

      // 🔥 READ FROM FLASH
      memcpy_P(&L_temp, &layers[j], sizeof(Layer));
      Layer &L = L_temp;

      if (!active(L,t) || L.pumps[i]==-1) continue;

      float w = weight(L,t);
      float target = L.pumps[i];

      cur = (cur<0)?target:(cur*(1-w)+target*w);
    }

    if (cur>=0) pump_out[i]=cur;
  }

  // ===== OUTPUT =====
  for (int i=0;i<N_MOTORS;i++)
    motors[i].write(constrain((int)motor_out[i],0,180));

  for (int i=0;i<N_PUMPS;i++)
    analogWrite(pumpPins[i], constrain((int)pump_out[i],0,255));

  delay(10);
}
